const fn make_tables() -> [[u64; 256]; 8] {
    let mut tables = [[0u64; 256]; 8];
    let mut table = 0;
    while table < 8 {
        let mut byte = 0;
        while byte < 256 {
            let substituted = PI[byte];
            let mut value = 0u64;
            let mut bit = 0;
            while bit < 8 {
                if substituted & (1 << (7 - bit)) != 0 {
                    value ^= A[(7 - table) * 8 + bit];
                }
                bit += 1;
            }
            tables[table][byte] = value.swap_bytes();
            byte += 1;
        }
        table += 1;
    }
    tables
}

const TABLES: [[u64; 256]; 8] = make_tables();

#[inline]
fn xor_512(left: &mut [u8; 64], right: &[u8; 64]) {
    for (left, right) in left.iter_mut().zip(right) {
        *left ^= *right;
    }
}

/// Combined S, P, and L transformation. `TABLES` is generated from the
/// specification constants at compile time and matches bc-csharp's fixed `T`.
/// Variable time: each output word indexes the tables with bytes of `value`.
fn transform(value: &mut [u8; 64]) {
    let input = *value;
    for column in 0..8 {
        let mut result = 0u64;
        for table in 0..8 {
            result ^= TABLES[table][input[56 - table * 8 + column] as usize];
        }
        value[column * 8..column * 8 + 8].copy_from_slice(&result.to_le_bytes());
    }
}

/// The compression function g_N(h, m) with N = `count`.
/// Variable time: it runs the table-driven transformation.
fn compression(state: &mut [u8; 64], count: &[u8; 64], message: &[u8; 64]) {
    let previous = *state;
    xor_512(state, count);
    transform(state);

    let mut round_key = *state;
    xor_512(state, message);
    transform(state);
    for constant in &ROUND_CONSTANTS[..11] {
        xor_512(&mut round_key, constant);
        transform(&mut round_key);
        xor_512(state, &round_key);
        transform(state);
    }
    xor_512(&mut round_key, &ROUND_CONSTANTS[11]);
    transform(&mut round_key);
    xor_512(state, &round_key);

    xor_512(state, &previous);
    xor_512(state, message);
}

/// Adds `addend` to the big-endian length counter. Constant time with respect
/// to the message: the carry depends only on the public message length.
fn add_u32(value: &mut [u8; 64], addend: u32) {
    let mut carry = addend;
    for byte in value.iter_mut().rev() {
        carry += *byte as u32;
        *byte = carry as u8;
        carry >>= 8;
        if carry == 0 {
            break;
        }
    }
}

/// Adds `addend` to `value` modulo 2^512, both big-endian. Constant time.
fn add_512(value: &mut [u8; 64], addend: &[u8; 64]) {
    let mut carry = 0u16;
    for (value, addend) in value.iter_mut().rev().zip(addend.iter().rev()) {
        carry += *value as u16 + *addend as u16;
        *value = carry as u8;
        carry >>= 8;
    }
}

/// The state both Streebog output sizes share. Every array is big-endian, as
/// in the standard and Bouncy Castle.
#[derive(Clone)]
struct Gost3411_2012Core {
    /// The byte every byte of the IV takes: 0x01 for 256 bits, 0 for 512.
    iv: u8,
    /// The number of message bits processed, N.
    count: [u8; 64],
    /// The running sum Σ of the message blocks, modulo 2^512.
    checksum: [u8; 64],
    /// The chaining value h.
    state: [u8; 64],
    /// The block being filled, from its last byte down.
    block: [u8; 64],
    /// The index of the last byte filled in `block`, 64 when it is empty.
    block_offset: usize,
}

impl Gost3411_2012Core {
    /// Creates a state with every IV byte set to `iv`. Constant time.
    const fn new(iv: u8) -> Self {
        Gost3411_2012Core {
            iv,
            count: [0; 64],
            checksum: [0; 64],
            state: [iv; 64],
            block: [0; 64],
            block_offset: 64,
        }
    }

    /// Compresses one full message block and adds it to the length and the
    /// checksum. Variable time: it runs the table-driven compression.
    fn process_block(&mut self, block: &[u8; 64]) {
        compression(&mut self.state, &self.count, block);
        add_u32(&mut self.count, 512);
        add_512(&mut self.checksum, block);
    }

    /// Buffers one byte, compressing the block once it is full.
    /// Variable time: a full block runs the compression.
    fn update_byte(&mut self, byte: u8) {
        self.block_offset -= 1;
        self.block[self.block_offset] = byte;
        if self.block_offset == 0 {
            let block = self.block;
            self.process_block(&block);
            self.block_offset = 64;
        }
    }

    /// Absorbs `input`, compressing whole blocks directly.
    /// Variable time: it runs the compression.
    fn update(&mut self, mut input: &[u8]) {
        while self.block_offset != 64 && !input.is_empty() {
            self.update_byte(input[0]);
            input = &input[1..];
        }

        while input.len() >= 64 {
            let mut block = [0u8; 64];
            for (destination, source) in block.iter_mut().rev().zip(&input[..64]) {
                *destination = *source;
            }
            self.process_block(&block);
            input = &input[64..];
        }

        for &byte in input {
            self.update_byte(byte);
        }
    }

    /// Pads and compresses the final block, the length and the checksum,
    /// returns the 64-byte result in output order and resets.
    /// Variable time: it runs the compression.
    fn finalize(&mut self) -> [u8; 64] {
        let message_length = 64 - self.block_offset;
        let mut message = [0u8; 64];
        message[63 - message_length] = 1;
        if message_length != 0 {
            message[64 - message_length..].copy_from_slice(&self.block[self.block_offset..]);
        }

        compression(&mut self.state, &self.count, &message);
        add_u32(&mut self.count, (message_length * 8) as u32);
        add_512(&mut self.checksum, &message);
        compression(&mut self.state, &[0; 64], &self.count);
        compression(&mut self.state, &[0; 64], &self.checksum);

        let mut result = self.state;
        result.reverse();
        self.reset();
        result
    }

    /// Wipes the length, checksum, state and buffered block, then restores
    /// the IV. Constant time.
    fn reset(&mut self) {
        self.zeroize();
        self.state = [self.iv; 64];
        self.block_offset = 64;
    }
}

impl Zeroize for Gost3411_2012Core {
    /// Wipes the length, checksum, state, buffered block and offset with
    /// volatile writes, keeping the IV byte. Constant time.
    fn zeroize(&mut self) {
        self.count.zeroize();
        self.checksum.zeroize();
        self.state.zeroize();
        self.block.zeroize();
        self.block_offset.zeroize();
    }
}

impl Drop for Gost3411_2012Core {
    /// Wipes the length, checksum, state and buffered block. Constant time.
    fn drop(&mut self) {
        self.zeroize();
    }
}

