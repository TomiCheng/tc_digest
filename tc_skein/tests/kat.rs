/// Decodes a hex string.
fn decode(hex: &str) -> Vec<u8> {
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
        .collect()
}

/// Hashes `message` under `params` and returns the digest as hex.
fn skein<P: SkeinParams + ?Sized>(
    state: usize,
    output: usize,
    params: &P,
    message: &[u8],
) -> String {
    let mut digest = SkeinDigest::new(state, output);
    digest.init(params).unwrap();
    digest.update(message);
    let mut out = vec![0u8; output / 8];
    digest.do_final(&mut out);
    out.iter().map(|b| format!("{b:02x}")).collect()
}

