//! `Dstu7564Digest`.
//!
//! The 256-bit digest runs a 512-bit state of eight 64-bit columns for 10
//! rounds; the 384- and 512-bit digests run a 1024-bit state of sixteen
//! columns for 14 rounds. Each block `M` updates the state `H` to
//! `H ^ P(H ^ M) ^ Q(M)`, and the output transformation `H ^ P(H)` gives the
//! digest from the last columns.

