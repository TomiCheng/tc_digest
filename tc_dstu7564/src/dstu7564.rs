/// Replaces every byte of the state `s` through the S-box of its row (Bouncy
/// Castle `SubBytes`). Variable time: the S-box index is a byte of the state,
/// so the memory access pattern depends on the message.
fn sub_bytes(s: &mut [u64]) {
    for column in s {
        let b = column.to_le_bytes();
        *column = u64::from_le_bytes([
            S0[b[0] as usize],
            S1[b[1] as usize],
            S2[b[2] as usize],
            S3[b[3] as usize],
            S0[b[4] as usize],
            S1[b[5] as usize],
            S2[b[6] as usize],
            S3[b[7] as usize],
        ]);
    }
}

/// Multiplies one column by the circulant MDS matrix
/// `(0x01, 0x01, 0x05, 0x01, 0x08, 0x06, 0x07, 0x04)` over GF(2^8) modulo
/// `x^8 + x^4 + x^3 + x^2 + 1` (Bouncy Castle `MixColumn`), with Bouncy
/// Castle's shared partial sums. Constant time.
fn mix_column(c: u64) -> u64 {
    // Every byte multiplied by x.
    let x1 = ((c & 0x7f7f_7f7f_7f7f_7f7f) << 1) ^ (((c & 0x8080_8080_8080_8080) >> 7) * 0x1d);

    let mut u = c.rotate_right(8) ^ c;
    u ^= u.rotate_right(16);
    u ^= c.rotate_right(48);

    // Every byte multiplied by x^2.
    let mut v = u ^ c ^ x1;
    v = ((v & 0x3f3f_3f3f_3f3f_3f3f) << 2)
        ^ (((v & 0x8080_8080_8080_8080) >> 6) * 0x1d)
        ^ (((v & 0x4040_4040_4040_4040) >> 6) * 0x1d);

    u ^ v.rotate_right(32) ^ x1.rotate_right(40) ^ x1.rotate_right(48)
}

/// Applies the round function after the round constants: `ShiftRows`,
/// `SubBytes` and `MixColumns`. Variable time, through `sub_bytes`.
fn permute_round(s: &mut [u64]) {
    shift_rows(s);
    sub_bytes(s);
    for column in s {
        *column = mix_column(*column);
    }
}

/// The permutation P (Bouncy Castle `P`): each round XORs a constant into
/// every column, then runs the round function. Variable time, through
/// `sub_bytes`.
fn permute_p(s: &mut [u64], rounds: usize) {
    for round in 0..rounds {
        let mut rc = round as u64;
        for column in s.iter_mut() {
            *column ^= rc;
            rc += 0x10;
        }
        permute_round(s);
    }
}

/// The permutation Q (Bouncy Castle `Q`): each round adds a constant to every
/// column modulo 2^64, then runs the round function. Variable time, through
/// `sub_bytes`.
fn permute_q(s: &mut [u64], rounds: usize) {
    for round in 0..rounds {
        let mut rc = ((((s.len() - 1) << 4) ^ round) as u64) << 56 | 0x00f0_f0f0_f0f0_f0f3;
        for column in s.iter_mut() {
            *column = column.wrapping_add(rc);
            rc = rc.wrapping_sub(0x1000_0000_0000_0000);
        }
        permute_round(s);
    }
}

/// Compresses one block of little-endian columns into the state `h`, as
/// `h ^ P(h ^ m) ^ Q(m)` (Bouncy Castle `ProcessBlock`). Variable time,
/// through `sub_bytes`.
fn compress(h: &mut [u64], block: &[u8], rounds: usize) {
    let mut p = [0u64; WIDE_COLUMNS];
    let mut q = [0u64; WIDE_COLUMNS];
    let columns = h.len();
    for (((p, q), &h), chunk) in p
        .iter_mut()
        .zip(q.iter_mut())
        .zip(h.iter())
        .zip(block.chunks_exact(8))
    {
        let m = u64::from_le_bytes(chunk.try_into().expect("8-byte chunk"));
        *p = h ^ m;
        *q = m;
    }

    permute_p(&mut p[..columns], rounds);
    permute_q(&mut q[..columns], rounds);

    for ((h, p), q) in h.iter_mut().zip(p).zip(q) {
        *h ^= p ^ q;
    }
}

/// The block buffer, sized by the state the digest length selects.
#[derive(Clone)]
enum Buffer {
    /// 64-byte blocks for the 512-bit state of the 256-bit digest.
    Narrow(MdBuffer<64>),
    /// 128-byte blocks for the 1024-bit state of the longer digests.
    Wide(MdBuffer<128>),
}

/// The DSTU 7564:2014 (Kupyna) digest with a 256-, 384- or 512-bit output.
///
/// Variable time: the permutations index S-boxes with bytes of the state,
/// which can leak the message through cache timing. Hash only public data
/// with it, or accept that leak in the threat model.
///
/// Dropping or resetting the digest, which `do_final` also does, wipes its
/// chaining state and buffered input with volatile writes. Copies the
/// compression leaves in registers or on the stack, such as the permuted
/// states, and copies a move leaves behind are not wiped.
///
/// `do_final` panics if the output buffer is shorter than the digest.
#[derive(Clone)]
pub struct Dstu7564Digest {
    /// The chaining state; the 512-bit state uses the first eight columns.
    state: [u64; WIDE_COLUMNS],
    /// The block buffer.
    buf: Buffer,
    /// The digest length in bytes: 32, 48 or 64.
    digest_size: usize,
}

impl Dstu7564Digest {
    /// Creates a DSTU 7564 digest with a `bit_length` of 256, 384 or 512.
    /// Constant time.
    ///
    /// # Panics
    ///
    /// Panics if `bit_length` is not 256, 384 or 512, as Bouncy Castle throws
    /// an `ArgumentException`.
    pub fn new(bit_length: usize) -> Self {
        assert!(
            matches!(bit_length, 256 | 384 | 512),
            "DSTU 7564 bit length must be 256, 384 or 512"
        );
        let buf = if bit_length == 256 {
            Buffer::Narrow(MdBuffer::new())
        } else {
            Buffer::Wide(MdBuffer::new())
        };
        let mut digest = Dstu7564Digest {
            state: [0; WIDE_COLUMNS],
            buf,
            digest_size: bit_length / 8,
        };
        digest.state[0] = digest.byte_length() as u64;
        digest
    }

    /// The columns of the state in use and the number of rounds.
    /// Constant time.
    fn shape(&self) -> (usize, usize) {
        match self.buf {
            Buffer::Narrow(_) => (NARROW_COLUMNS, NARROW_ROUNDS),
            Buffer::Wide(_) => (WIDE_COLUMNS, WIDE_ROUNDS),
        }
    }
}

/// The 96-bit little-endian bit length of a message of `byte_count` bytes.
/// Constant time.
fn length_field(byte_count: u64) -> [u8; 12] {
    let bits = (u128::from(byte_count) << 3).to_le_bytes();
    let mut field = [0u8; 12];
    field.copy_from_slice(&bits[..12]);
    field
}

impl Drop for Dstu7564Digest {
    /// Wipes the chaining state; the block buffer wipes itself.
    /// Constant time.
    fn drop(&mut self) {
        self.state.zeroize();
    }
}

impl fmt::Display for Dstu7564Digest {
    /// Writes `DSTU7564` without inspecting the digest state. Constant time
    /// with respect to the message; output timing depends on the formatter.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("DSTU7564")
    }
}

impl TryDigest for Dstu7564Digest {
    type Error = Infallible;

    fn digest_size(&self) -> usize {
        self.digest_size
    }

    fn byte_length(&self) -> usize {
        match self.buf {
            Buffer::Narrow(_) => 64,
            Buffer::Wide(_) => 128,
        }
    }

    fn try_update(&mut self, input: &[u8]) -> Result<(), Self::Error> {
        let Self { state, buf, .. } = self;
        match buf {
            Buffer::Narrow(buf) => buf.update(input, |block| {
                compress(&mut state[..NARROW_COLUMNS], block, NARROW_ROUNDS)
            }),
            Buffer::Wide(buf) => buf.update(input, |block| compress(state, block, WIDE_ROUNDS)),
        }
        Ok(())
    }

    /// Writes the digest to the start of `output` and resets.
    ///
    /// # Panics
    ///
    /// Panics if `output` is shorter than the digest, before changing any
    /// state.
    fn try_do_final(&mut self, output: &mut [u8]) -> Result<usize, Self::Error> {
        let digest_size = self.digest_size;
        assert!(
            output.len() >= digest_size,
            "output buffer shorter than the DSTU 7564 digest"
        );
        let (columns, rounds) = self.shape();
        {
            let Self { state, buf, .. } = self;
            match buf {
                Buffer::Narrow(buf) => {
                    let length = length_field(buf.byte_count());
                    buf.finish(&length, |block| {
                        compress(&mut state[..NARROW_COLUMNS], block, NARROW_ROUNDS)
                    });
                }
                Buffer::Wide(buf) => {
                    let length = length_field(buf.byte_count());
                    buf.finish(&length, |block| compress(state, block, WIDE_ROUNDS));
                }
            }

            // The output transformation H ^ P(H); the digest is its last
            // columns.
            let state = &mut state[..columns];
            let mut transformed = [0u64; WIDE_COLUMNS];
            transformed[..columns].copy_from_slice(state);
            permute_p(&mut transformed[..columns], rounds);
            for (h, t) in state.iter_mut().zip(transformed) {
                *h ^= t;
            }
            let tail = &state[columns - digest_size / 8..];
            for (chunk, word) in output.chunks_exact_mut(8).zip(tail) {
                chunk.copy_from_slice(&word.to_le_bytes());
            }
        }
        self.try_reset()?;
        Ok(digest_size)
    }

    fn try_reset(&mut self) -> Result<(), Self::Error> {
        *self = Self::new(self.digest_size * 8);
        Ok(())
    }
}
