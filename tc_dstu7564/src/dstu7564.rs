            exchange(c1, c5, 0x00ff_ffff_ff00_0000);
            exchange(c2, c6, 0x0000_ffff_ffff_0000);
            exchange(c3, c7, 0x0000_00ff_ffff_ff00);

            exchange(c0, c2, 0xffff_0000_ffff_0000);
            exchange(c1, c3, 0x00ff_ff00_00ff_ff00);
            exchange(c4, c6, 0xffff_0000_ffff_0000);
            exchange(c5, c7, 0x00ff_ff00_00ff_ff00);

            exchange(c0, c1, 0xff00_ff00_ff00_ff00);
            exchange(c2, c3, 0xff00_ff00_ff00_ff00);
            exchange(c4, c5, 0xff00_ff00_ff00_ff00);
            exchange(c6, c7, 0xff00_ff00_ff00_ff00);
