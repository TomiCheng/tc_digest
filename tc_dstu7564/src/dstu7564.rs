/// Exchanges the bits of `a` and `b` that `mask` selects. Constant time.
#[inline(always)]
fn exchange(a: &mut u64, b: &mut u64, mask: u64) {
    let d = (*a ^ *b) & mask;
    *a ^= d;
    *b ^= d;
}

/// Rotates byte row `i` of the state `s` by `i` columns, and in the 1024-bit
/// state row 7 by 11 (Bouncy Castle `ShiftRows`), with Bouncy Castle's
/// network of masked exchanges. Constant time.
